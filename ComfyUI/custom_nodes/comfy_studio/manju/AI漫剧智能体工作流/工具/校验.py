def check_assets(files):
    """检查 6：素材完整性 —— 参考 md / 规格原文是否被误删。

    依据用户明确要求：参考的 md 很有用，尽量保留、不要删除。
    注意：本检查直接查文件系统（不依赖 walk_files 的扩展名过滤），
          否则 .py 等非 md/yaml 文件会被误判为缺失。
    """
    failures = []

    for req in REQUIRED_FILES:
        if not os.path.exists(os.path.join(ROOT, req)):
            failures.append({
                "rule": "素材缺失",
                "file": req,
                "line": 0,
                "text": "该文件应存在但未找到（是否被误删？）",
                "should_be": "恢复该文件",
            })

    for d, min_n, desc in REQUIRED_DIR_MIN:
        absdir = os.path.join(ROOT, d)
        if not os.path.isdir(absdir):
            n = 0
        else:
            n = sum(len(fns) for _, _, fns in os.walk(absdir))
        if n < min_n:
            failures.append({
                "rule": "素材缺失",
                "file": f"{d}/（{desc}）",
                "line": 0,
                "text": f"实际 {n} 个文件，应不少于 {min_n} 个（是否被批量误删？）",
                "should_be": f"补回至 ≥ {min_n} 个",
            })

    # 反向守卫：**不该存在**的重复副本（动机见 FORBIDDEN_PATHS 上方注释）
    for rel, why in FORBIDDEN_PATHS:
        if os.path.exists(os.path.join(ROOT, rel)):
            failures.append({
                "rule": "重复副本",
                "file": f"{rel}/",
                "line": 0,
                "text": f"该路径**不应存在**：{why}",
                "should_be": "删除它；实体目录只由 `python main.py project new <项目名>` 生成",
            })

    # 工作区级素材：按**文件名**在整个工作区递归核对
    #
    # ⚠️⚠️ 判据是「**内容在不在**」，不是「**在不在 `data/`**」。
    #   本检查第一版只在 `data/` 下搜 —— 而它**自己的注释**就写着
    #   「用户会整理 …（如把规格移入 智能体搭建参考md/）」。
    #   实测后果（2026-09-26）：用户把那 6 份原始规格整理到了仓库根的
    #   `智能体搭建参考md/`，于是**6 份全报"被误删"**，而它们好好地在。
    #   **检查器的误报和代码 bug 一样耗人** —— 它会逼你去"恢复"一个没丢的文件。
    #   故改为全工作区按文件名核对（跳过 SKIP_DIRS 与点目录）。
    names = set()
    for _dp, _dns, _fns in os.walk(WORKSPACE):
        _dns[:] = [d for d in _dns if d not in SKIP_DIRS and not d.startswith(".")]
        names.update(_fns)
    import fnmatch
    for req in REQUIRED_WORKSPACE_FILES:
        if not any(fnmatch.fnmatch(n, req) for n in names):
            failures.append({
                "rule": "原始规格缺失",
                "file": req,
                "line": 0,
                "text": "整个工作区都未搜到匹配该模式的原始规格（是否被误删？）",
                "should_be": "恢复该文件（放在 data/ 或 智能体搭建参考md/ 均可）",
            })
    return failures


def check_text_integrity(files):
    """检查 7：文本完整性 —— 全角括号配平 + 已知损坏指纹。

    背景（2026-09-23 实际事故）：
      用 PowerShell 批量替换中文文本时，`@(@("a","b"))` 这类**单元素数组会被展开**，
      于是 `foreach` 拿到的是字符串而非数组，`.Replace($pair[0], $pair[1])`
      退化成**字符级替换**（`$pair[0]` 取到的是首字符）：
        · 想替换「视觉分镜引擎.md …」→ 实际把全文所有「视」换成了「觉」
        · 想替换「676 行 / 27.4 KB」  → 实际把全文所有「6」换成「7」再把「7」换成「3」
      结果 3 个文件被静默损坏，而当时没有任何检查能发现。

    **最可靠的信号 = 全角括号不配对**：正常中文文档里 `（` 与 `）` 逐行配平，
    字符级替换极易打破它（把 `（` 换成数字/汉字）。
    另加一组**已知损坏指纹**（正常项目不该出现的组合）作双保险。

    ⚠️ 结论：**不要用 PowerShell / sed 做中文内容的批量替换**，改用编辑工具（走 Python）。
    """
    # 已知损坏指纹：这些组合在正常中文里不存在（均由字符级替换产生）
    FINGERPRINTS = [
        ("觉觉", "视觉"),        # 「视觉」被换成「觉觉」
        ("觉频", "视频"),        # 「视频」被换成「觉频」
        ("三觉图", "三视图"),    # 「三视图」被换成「三觉图」
        ("13:9", "16:9"),        # '6'→'3' 类数字损坏
    ]
    # 容忍阈值：中文文档里偶有笑脸 :) 等排版特例，单行不配对不报；
    # 真正的字符级替换会**成片**破坏配平（实测一次事故 = 25 行）
    UNBALANCED_LINE_TOLERANCE = 2
    FILE_IMBALANCE_TOLERANCE = 2
    # 本检查的文档与实现必须「列出」这些指纹（说明性文字），豁免指纹扫描；
    # 括号配平仍检查（这些文件里是 ASCII 括号，不受影响）
    FINGERPRINT_EXEMPT_FILES = ("工具/README.md", "工具/校验.py")

    failures = []

    for ap, rel in files:
        text = read(ap)
        if text is None:
            continue

        # ① 文件级全角括号配平（先看整体，抗单行噪声）
        o, c = text.count("（"), text.count("）")
        if abs(o - c) >= FILE_IMBALANCE_TOLERANCE:
            # 定位最可疑的若干行
            unbal = [(i, l) for i, l in enumerate(text.splitlines(), 1)
                     if l.count("（") != l.count("）")]
            if len(unbal) >= UNBALANCED_LINE_TOLERANCE:
                for i, l in unbal[:5]:
                    failures.append({
                        "rule": "括号不配对（疑似字符级替换损坏）",
                        "file": rel, "line": i,
                        "text": l.strip()[:100],
                        "should_be": "全角括号逐行配平",
                    })
                if len(unbal) > 5:
                    failures.append({
                        "rule": "括号不配对（续）", "file": rel, "line": 0,
                        "text": f"共 {len(unbal)} 行不配对，此处仅列前 5 行",
                        "should_be": "全角括号逐行配平",
                    })

        # ② 已知损坏指纹（豁免本检查自身的文档与实现）
        if rel in FINGERPRINT_EXEMPT_FILES:
            continue
        for bad, good in FINGERPRINTS:
            if bad in text:
                idx = text.find(bad)
                ln = text[:idx].count("\n") + 1
                lines = text.splitlines()
                failures.append({
                    "rule": f"损坏指纹「{bad}」",
                    "file": rel, "line": ln,
                    "text": lines[ln - 1].strip()[:100] if ln <= len(lines) else "",
                    "should_be": good,
                })
    return failures


def check_numeric_claims(files):
    """检查 8：数字声明一致性 —— 文档里写的体积 / 行数 / 个数是否与现状一致。

    背景：数字声明是本项目的**高发失效点**，历史已踩过 4 次以上：
      · 合并版从 77.3KB 去重到 30KB 后，多处文档仍写旧数字
      · 部署指南的「体积表」8 项数据全部过时
      · PowerShell `(Get-Content).Count` 误计行数（1824），正确是 2344——
        而且只改了索引、漏改正文 2 处
      · 根 README 写「102 个文件 / 753 KB」，实际 123 / 1230

    设计要点（三条都是实测踩出来的假阳性，缺一不可）：
      ① **只检查全项目唯一的文件名** —— `00-主控智能体.md` 在 5 个模块都存在，
         无法判断文档指的是哪一个，强行比较必然误报
      ② **跳过含 `→` 的行** —— 那是提炼过程描述（「2344 行 → 481 行」），不是现状声明
      ③ **跳过同一行有 ≥2 个同类数字的** —— 那是「前后对比」写法
         （版本说明「实跑时 724 行…现为 777 行」、错误日志「1824 行 | 2344 行」），
         此时无法判断该拿哪个数字当"现状"，跳过比乱报好
    """
    from collections import defaultdict
    failures = []

    # 文件名 → 出现位置（仅唯一的才参与比对）
    by_base = defaultdict(list)
    for ap, rel in files:
        by_base[os.path.basename(ap)].append(ap)
    uniq = {b: v[0] for b, v in by_base.items() if len(v) == 1}

    local_paths = [ap for ap, _ in files]
    local_cnt = len([ap for ap in local_paths if ap.endswith((".md", ".yaml"))])
    local_kb = sum(file_kb(ap) for ap in local_paths
                   if ap.endswith((".md", ".yaml")))

    KB = re.compile(r"`([^`\n]+\.(?:md|py|yaml))`\s*[|｜]\s*\**\s*([0-9]+(?:\.[0-9])?)\s*KB")
    LN = re.compile(r"([0-9]{2,5})\s*行")
    NAME = re.compile(r"`([^`\n]+\.(?:md|yaml))`")
    CNT = re.compile(r"([\u4e00-\u9fa5A-Za-z]+)/?\s*[（(]\s*([0-9]{1,2})\s*个")
    DIRMAP = {"引擎": "02-服化道/引擎", "模板": "02-服化道/模板",
              "源skill库": "02-服化道/源skill库"}

    def line_of(t, pos):
        return t[:pos].count("\n") + 1

    def line_text(t, pos):
        a = t.rfind("\n", 0, pos) + 1
        b = t.find("\n", pos)
        return t[a: b if b != -1 else len(t)]

    def is_before_after(line, pat):
        """同一行出现 ≥2 个同类数字 → 是「前后对比」写法，不判过时。"""
        return len(pat.findall(line)) >= 2

    KB_NUM = re.compile(r"[0-9]+(?:\.[0-9])?\s*KB")
    LN_NUM = re.compile(r"[0-9]+\s*行")

    for ap, rel in files:
        t = read(ap)
        if not t:
            continue
        # ① 体积声明
        for m in KB.finditer(t):
            name, kb = os.path.basename(m.group(1)), float(m.group(2))
            line = line_text(t, m.start())
            if name not in uniq or "→" in line or is_before_after(line, KB_NUM):
                continue
            real = file_kb(uniq[name])
            if abs(real - kb) > 0.6:
                failures.append({
                    "rule": f"体积声明过时（{name}）", "file": rel,
                    "line": line_of(t, m.start()),
                    "text": f"写 {kb} KB，实际 {real:.1f} KB",
                    "should_be": f"{real:.1f} KB",
                })
        # ② 行数声明
        for m in LN.finditer(t):
            line = line_text(t, m.start())
            if "→" in line or "->" in line or is_before_after(line, LN_NUM):
                continue
            # ⚠️ 排除「**第** N 行」这类**位置引用** —— 它是"某内容在第几行"，
            #    不是"这个文件有 N 行"。两者判据不同，混在一起会给出**错的修改建议**
            #    （实测踩到：`ASSET_CARD.yaml 第 104 行注释`被读成"行数声明"，
            #     并建议"应改为 169 行"—— 那会把位置改成数量，越改越错）。
            if re.search(r"第\s*%s\s*行" % re.escape(m.group(1)), line):
                continue
            names = [os.path.basename(x) for x in NAME.findall(line)]
            names = [x for x in names if x in uniq]
            if len(names) != 1:
                continue
            real = read(uniq[names[0]]).count("\n") + 1
            if abs(real - int(m.group(1))) > 2:
                failures.append({
                    "rule": f"行数声明过时（{names[0]}）", "file": rel,
                    "line": line_of(t, m.start()),
                    "text": f"写 {m.group(1)} 行，实际 {real} 行",
                    "should_be": f"{real} 行",
                })
        # ③ 目录个数声明（排除索引 README，它不算一项内容）
        for m in CNT.finditer(t):
            label, n = m.group(1), int(m.group(2))
            sub = DIRMAP.get(label)
            if not sub or not os.path.isdir(os.path.join(ROOT, sub)):
                continue
            real = 0
            for _, _, fns in os.walk(os.path.join(ROOT, sub)):
                real += len([f for f in fns
                             if f.endswith((".md", ".yaml")) and f != "README.md"])
            if real != n:
                failures.append({
                    "rule": f"个数声明过时（{label}）", "file": rel,
                    "line": line_of(t, m.start()),
                    "text": f"写 {n} 个，实际 {real} 个",
                    "should_be": f"{real} 个",
                })
        # ④ 总量声明（排除小数字，如「64 个文件」指工作区素材）
        for m in re.finditer(r"([0-9]{3})\s*个文件", t):
            n = int(m.group(1))
            if abs(n - local_cnt) > 3:
                failures.append({
                    "rule": "总量声明过时", "file": rel,
                    "line": line_of(t, m.start()),
                    "text": f"写 {n} 个文件", "should_be": f"{local_cnt} 个",
                })
    return failures


def check_trees(files):
    """检查 9：目录树一致性 —— README 里画的树是否与实际文件对得上。

    背景（2026-09-23 用户报障）：
      根 README 的目录树出现三类失效，而前 8 类检查**全都发现不了**——
      因为目录树是"人类可读的结构描述"，不是路径式引用（检查 1 只抓 `` `路径` `` 反引号引用）：
        · **模块顺序乱**（迁移到新编号后仍按旧顺序 03→02→04→05→01→06 排列）
        · **漏列真实内容**（`_archive/`、`99-源仓库索引/规格覆盖率审计.md`）
        · **数字过时**（Suno 引擎写 29KB 实为 30.6KB、合并版写 31KB 实为 31.9KB）

    口径（**必须收窄**，否则误报率极高）：
      · **只查「描述仓库结构」的 README** —— 根 `README.md` 与各模块 `0X-*/README.md`
        ❌ 不查：`引擎/`·`模板/`·`_规格原文/`·`源skill库/` 下的文件与 `项目骨架/README.md`，
           因为它们的「树」是**概念结构图 / 骨架示意 / 外部目录树**，本就不该存在于仓库
        （首版未收窄 → 一次误报 45 项：概念图里的 `§4.2`/`C`/`B2`、骨架里的
          `PROJECT_STATE`/`CHARACTER_001`、`data/资料` 的外部目录、ASCII 框线等）
      · 文件条目在该 README **子树内按 basename** 匹配（树里常只写文件名）
      · 跳过**图示块**：多数行含 `→`（接线图），或条目本身是**纯框线字符**
    """
    TREE = re.compile(r"^[│├└─\s]*[│├└]──\s*([^\s←⭐]+)", re.M)
    BOX = re.compile(r"^[─│┌┐└┘├┤┬┴┼\s]+$")
    failures = []

    for ap, rel in files:
        # ① 文件范围收窄
        base_name = os.path.basename(ap)
        if base_name != "README.md":
            continue
        if "项目骨架" in rel or "_archive" in rel or "示例演示" in rel:
            continue
        if rel != "README.md" and not re.match(r"^0[1-8]-[^/]+/README\.md$", rel):
            continue

        text = read(ap)
        if not text:
            continue
        base = os.path.dirname(ap)
        names, dirs = set(), set()
        for dp, dns, fns in os.walk(base):
            names.update(fns)
            dirs.update(dns)
        if not names:
            continue

        # ⚠️ 语言标签必须**任意接受**（`[^\n]*`），只认 `text` 会让代码块**配对错位**：
        #    实测（2026-09-27）`08-项目管理/README.md` 里 ` ```bash ` 块在前、` ```text ` 树块在后，
        #    正则从 bash 块的**结束**围栏开始配对，把中间的说明段当成块内容，
        #    真正的树块再没机会被当作开头 —— 结果**这个检查对该文件静默失效**
        #    （注入一个不存在的树条目也照样 PASS）。07 的 README 同样如此。
        for block in re.findall(r"```[^\n]*\n(.*?)```", text, re.S):
            entries = [TREE.match(l).group(1) for l in block.splitlines() if TREE.match(l)]
            if not entries:
                continue
            # ② 跳过图示块
            arrow = sum(1 for l in block.splitlines() if "→" in l)
            if arrow > len(entries) * 0.5:
                continue

            for ent in entries:
                ent = ent.strip().rstrip("/")
                if not ent or ent.startswith(("*", "…", "(")) or ent in (".", ".."):
                    continue
                if BOX.match(ent):            # 纯框线字符（ASCII 框图）
                    continue
                bn = ent.split("/")[-1]
                if "<" in bn or "…" in bn:    # 占位符
                    continue
                is_dir = ent.endswith("/") or "." not in bn
                ok = (bn in dirs) if is_dir else (bn in names)
                if not ok:
                    ln = 0
                    for i, l in enumerate(text.splitlines(), 1):
                        m = TREE.match(l)
                        if m and m.group(1).strip().rstrip("/") == ent:
                            ln = i
                            break
                    failures.append({
                        "rule": f"目录树条目不存在（{'目录' if is_dir else '文件'}）",
                        "file": rel, "line": ln,
                        "text": ent,
                        "should_be": "改为实际存在的名称，或从树中删除",
                    })
    return failures


# ─────────────────────────────────────────────────────────────
# 检查 12 的规则：档位系统名
# ─────────────────────────────────────────────────────────────
# 这些「系统名」若在 frontmatter 的 description 里被声明为「N 系统名」，
# 就必须与同文件章节标题里的「系统名（M 级/种）」一致。
SCALE_SYSTEMS = ["景别", "角度", "构图", "运动", "光影"]


def check_scale_claims(files):
    """检查 12：档位声明一致性 —— 文档自己声明自己。

    背景（2026-09-23，就在修 v41 的收尾时发现）：
      `03-分镜导演/视觉分镜引擎.md` 的 **frontmatter description** 写着
        「6 景别/7 角度/6 构图/13 运动/7 光影系统」，
      而同文件 §4.2–§4.6 的标题实际是
        「镜头景别系统（**7 级**）」「摄影机角度系统（**8 种**）」「构图系统（**9 种**）」
        「摄影机运动（13 种）」「光影系统（**8 种** + 氛围词）」
      —— **同一个文件自己跟自己矛盾**，而 frontmatter 是用户看到的「技能描述」。

      而且不是第一次：景别/角度的声明**改过了**，构图/光影的**漏改了** ——
      「改一半」是本项目的高发形态（同 §五·4「改权威层必须同步实体层」）。

    设计优势：**纯文件内比对** —— 不涉及跨文件歧义，天然低误报。
      （对比：叙事分镜引擎合法地写「景别七级 / 角度五式 / 构图六法」，
        那是**另一个文件**，本检查互不影响。）

    口径（两条都要，缺一必然误报）：
      ① 只在 **YAML frontmatter 的 `description:`** 里找「N 系统名」声明
      ② 只认**编号子章节标题**（`### 4.2 …（N 级/种）`）作为「实际档位」；
         `### 2.7 光影` 这种没有「（N 种）」的标题不算，避免误判
    """
    failures = []
    HEADING = re.compile(r"^#{2,4}\s*[0-9]+\.[0-9]+.*$")          # 编号子章节
    SCALE = re.compile(r"（\s*([0-9]+)\s*(?:级|种|个|元素)")       # （7 级）/（9 种）

    for ap, rel in files:
        text = read(ap)
        if not text:
            continue
        fm = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n", text, re.S)
        if not fm:
            continue
        desc = fm.group(1)

        # ① 本文件章节标题里声明的「实际档位」
        actual = {}
        for line in text.splitlines():
            if not HEADING.match(line):
                continue
            for sysname in SCALE_SYSTEMS:
                if sysname in line and sysname not in actual:
                    m = SCALE.search(line)
                    if m:
                        actual[sysname] = (int(m.group(1)), line.strip()[:60])
        if not actual:
            continue

        # ② frontmatter 里声明的档位，逐个比对
        for sysname, (real, title) in actual.items():
            for dm in re.finditer(r"([0-9]+)\s*" + re.escape(sysname), desc):
                if int(dm.group(1)) != real:
                    ln = text[:fm.end()].count("\n")
                    failures.append({
                        "rule": f"档位声明与自身章节不符（{sysname}）",
                        "file": rel, "line": max(1, ln),
                        "text": f"frontmatter 写「{dm.group(0).strip()}」，"
                                f"但 {title}",
                        "should_be": f"改 frontmatter 为「{real} {sysname}」",
                    })
    return failures


CN_NUMS = "一二三四五六七八九十"


def _cn_to_int(s):
    """'一'→1 … '十'→10（本项目的章节号不超过十）"""
    s = s.strip()
    if s.isdigit():
        return int(s)
    return CN_NUMS.index(s) + 1 if s in CN_NUMS else None


def _headings(text):
    """抽出章节号集合与子节全号集合。

    项目里**两种标题风格并存**，必须都认：
      `## 五、光影设计的三个来源与分工`   （中文数字 + 、）
      `### 5.5 动作戏原则`               （阿拉伯 + 点）
    """
    secs, subs = set(), defaultdict(set)
    for l in text.splitlines():
        # ⚠️ 必须先认「多级点号编号」：否则 `### 3.5` 会被下面那条「章号 + 分隔符」
        #    规则抢走（读成「第 3 章 · 分隔符 . · 标题 5」），子节表就全空了
        m = re.match(r"^#{1,4}\s+§?\s*([0-9]+(?:\.[0-9]+)+)\s+\S", l)
        if m:
            full = m.group(1)
            secs.add(int(full.split(".")[0]))
            subs[int(full.split(".")[0])].add(full)
            continue
        m2 = re.match(r"^#{1,4}\s+§?\s*([0-9" + CN_NUMS + r"]+)\s*[、.．·]\s*\S", l)
        if m2:
            n = _cn_to_int(m2.group(1))
            if n:
                secs.add(n)
    return secs, subs


def check_structural_refs(files):
    """检查 10：结构引用一致性 —— 「手写的结构引用」能否解析到真实位置。

    背景（2026-09-23，检查 9 之后紧接着发现的**同类盲区**）：
      检查 9 覆盖了「README 的目录树」，但文档里还有两类**手写结构引用**同样无人检查：
        ① `【0N 模块名】` —— 流程图/正文里的模块编号
           v39 把模块重编号为「**编号 = 执行顺序**」（01 剧本文本 … 06 合规审核）。
           旧编号若残留（如 `【05 剧本文本】`），会把人指到**错误的模块**——而这是纯文字，
           检查 1（路径引用）和检查 9（目录树）都抓不到。
        ② `文件.md §X` —— 章节引用（文件改名 / 章节重排后失效）

    ⚠️ 收窄规则（7 条，全部是实测踩出来的，缺一即误报；首版一次误报 16 处）：
      a. **`§` 必须紧跟文件名（间隔 ≤2 字符）** —— 项目里有「覆盖度标注」写法：
         `` `PROJECT-PIPELINE.md` 生产流水线（§25 §26 §41）``，其中 §25 指的是
         **规格原文**的节号，不是该引擎文件的第 25 章
      b. **取 `§` 前面「最近」的 .md** —— `` `A.md` + `B.md` §1.5 `` 的 § 指 B 不指 A
      c. **非模块引用要排除** —— `【01 声音设计引擎】` 是模块**内部**引擎文件的序号，
         不是顶层模块；只在名称命中 `MODULE_NUMBERS` 时才校验
      d. **两种标题风格都要认**（见 `_headings`），且先认多级点号编号
      e. **目标文件找不到时交给检查 1**，此处不报（避免与检查 1 重复报同一问题）
      f. **`§` 的兜底解析只用全库唯一的 basename** —— `README.md` / `00-主控智能体.md`
         这类重名文件无法判断指哪一个，强行解析必然指错（同检查 8 的教训，见下方 ② 的注释）
      g. **`【0N 名称】` 的写法唯一**（2026-09-27 新增，见下方 ③）—— 数字与名称之间
         只留**一个半角空格**；`【0N-名称】`（连字符）与 `【0N名称】`（连写）都算错。
         ⚠️ 本子规则**不做名称白名单过滤**（与规则 c 相反）—— 连非模块引用
         （`【01 声音设计引擎】`）也必须写法统一，否则「写法」这件事本身就有两套标准。
         实测残留（2026-09-27 已修）：`05-音乐音频/README.md` 用**连字符**分隔、
         `00-总控路由.md` 的 frontmatter **不加空格**，而全库其余各级标题、流程图、
         README 共 40+ 处都是 `【0N 名称】`。
         ⚠️ 本规则扫**全部文件**（含本文件），故本文件里**不得写出反例的字面量** ——
         上面两处反例只能用占位符 `0N` 描述（`0N` 不是数字，不会自匹配）。
    """
    failures = []

    # ① `【0N 模块名】` 的编号是否与模块目录号一致
    for ap, rel in files:
        text = read(ap)
        if not text:
            continue
        for m in re.finditer(r"【\s*0?(\d{1,2})\s*-?\s*([^】]+)】", text):
            num = int(m.group(1))
            name = re.sub(r"^(本模块|模块)", "", m.group(2).strip()).strip()
            hit = next((k for k in MODULE_NUMBERS if k in name), None)
            if hit is None:
                continue                       # 规则 c
            if MODULE_NUMBERS[hit] != num:
                failures.append({
                    "rule": f"模块编号错误「【{m.group(1)} {name}】」",
                    "file": rel,
                    "line": text[:m.start()].count("\n") + 1,
                    "text": m.group(0),
                    "should_be": f"0{MODULE_NUMBERS[hit]}（该模块现编号）",
                })

    # ③ `【0N 名称】` 的**写法**是否唯一（2026-09-27 新增，规则 g）
    #    与 ① 的分工：① 管**编号对不对**（只在名称命中 MODULE_NUMBERS 时才校验），
    #    ③ 管**长得对不对**（**不做**白名单过滤 —— 连 `【01 声音设计引擎】` 这类
    #    模块内部引用也要合规，否则「写法」这件事本身就有两套标准）。
    #    正则：`【` + 可选空白 + **固定 `0` + 一位数字**（模块号恒为 `0N`）
    #          + **紧跟一个「非空白、非 `】`、非数字」的字符** + 80 字内闭合的 `】`。
    #    ⚠️ 三个约束必须**同时**在，少一个就误报（首版真踩过：一次误报 68 处）：
    #      · 固定 `0` —— 否则 `【40 集工业化拆解】`、`【5.1】`（小节号）都会被卷进来
    #      · 前瞻不含数字 —— 否则 `\d{1,2}` 会退化成只吃首位数字，于是 `【01 剧本文本】`
    #        的数字后「紧跟着非空白（即第 2 位数字）」而被判违规 —— 这是首版 68 处误报的根因
    #      · 80 字内闭合 —— 未闭合的 `【` 不至于吞到很远的 `】`；也够容下
    #        `【01 剧本文本 → … → 06 合规审核】` 这种整条流水线的写法
    #    前瞻只试探不吃字符（不破坏 ① 的解析）。
    #    ⚠️ 本规则扫**全部文件**（含本文件），故本文件里**不得写出**这两个反例的字面量。
    for ap, rel in files:
        text = read(ap)
        if not text:
            continue
        for m in re.finditer(r"【\s*0(\d)(?=[^\s】\d])[^】]{0,80}】", text):
            failures.append({
                "rule": f"模块引用写法不合规「{m.group(0)}」",
                "file": rel,
                "line": text[:m.start()].count("\n") + 1,
                "text": m.group(0),
                "should_be": "【0N 名称】（数字与名称之间只留一个半角空格；"
                             "没空格、用连字符都算错）",
            })

    # ② `文件.md §X` 的章节是否存在
    # 规则 f：兜底解析**只用全库唯一的 basename** —— `README.md` / `00-主控智能体.md`
    #         这类名字在多个目录都有，无法判断指哪一个，强行解析必然指错（同检查 8 的教训）
    by_base = defaultdict(list)
    for ap, rel in files:
        by_base[os.path.basename(ap)].append(ap)
    uniq_base = {b: v[0] for b, v in by_base.items() if len(v) == 1}
    head_cache = {}

    for ap, rel in files:
        text = read(ap)
        if not text:
            continue
        for i, line in enumerate(text.splitlines(), 1):
            for sm in re.finditer(
                    r"§\s*([0-9" + CN_NUMS + r"]+)\s*[·.．]?\s*([0-9]+(?:\.[0-9]+)*)?", line):
                head = line[:sm.start()]
                cands = list(re.finditer(r"([\w\-/\.]+\.md)", head))
                if not cands:
                    continue
                last = cands[-1]                # 规则 b
                if len(head) - last.end() > 2:  # 规则 a
                    continue
                sec_raw, sub = sm.group(1), sm.group(2)
                # 子节号还原为**全号**：
                #   §4.2    → sec='4' / sub='2'   → '4.2'
                #   §5.4.1  → sec='5' / sub='4.1' → '5.4.1'（子号已带点也要补章号）
                #   §五·5.5 → sec='五'（非数字）→ sub 本身已是全号，不动
                if sub and sec_raw.isdigit() and not sub.startswith(sec_raw + "."):
                    sub = f"{sec_raw}.{sub}"
                n = _cn_to_int(sec_raw)
                if n is None:
                    break
                tgt = os.path.normpath(os.path.join(os.path.dirname(ap), last.group(1)))
                if not os.path.exists(tgt):
                    tgt = uniq_base.get(os.path.basename(last.group(1)))
                    if not tgt:
                        break                   # 规则 e / f
                tgt = os.path.normpath(tgt)
                if tgt not in head_cache:
                    head_cache[tgt] = _headings(read(tgt))
                secs, subs = head_cache[tgt]
                trel = os.path.relpath(tgt, ROOT).replace("\\", "/")
                if n not in secs:
                    failures.append({
                        "rule": f"章节引用失效「{os.path.basename(last.group(1))} §{sec_raw}」",
                        "file": rel, "line": i,
                        "text": line.strip()[:100],
                        "should_be": f"{trel} 中无第 {n} 章",
                    })
                elif sub and sub not in subs.get(n, set()):
                    failures.append({
                        # sub 已是全号（如 '5.4.1'），不要再拼 sec_raw，否则成「§5·5.4.1」
                        "rule": f"子节引用失效「{os.path.basename(last.group(1))} §{sub}」",
                        "file": rel, "line": i,
                        "text": line.strip()[:100],
                        "should_be": f"{trel} 中无 {sub} 子节",
                    })
                break
    return failures


def _norm_header(s):
    return re.sub(r"\s+", "", s.strip())


def check_shared_headers(files):
    """检查 11：共享表头一致性 —— 同一张表在多个文件里的表头必须逐字相同。

    背景（2026-09-23）：
      「九列标准分镜表」的表头在**三处**重复定义（工作流 / 可部署合并版 / 实跑示例），
      「模块 ID 分配表」在三处重复。它们靠**人工保持一致**——而这是本项目第一号坑：

        改权威层却漏了实体层 → 用户复制到的仍是被取代的旧格式

      尤其 `分镜导演-完整合并版.md` 是**部署首选**（用户就是复制它的），
      它若没同步，用户拿到的列结构就是旧的。检查 2「机制覆盖」只能验证**关键词在不在**，
      无法验证**表头是否逐字相同**，故单列此项。

    口径：只认「表头行 + 紧随其后是分隔行」的**真表格**；比较时忽略空白差异。
    规则表见文件顶部 `SHARED_TABLE_HEADERS`。
    """
    contents = {rel: read(ap) for ap, rel in files}
    failures = []

    for rule in SHARED_TABLE_HEADERS:
        want = "| " + " | ".join(rule["cells"]) + " |"
        for f in rule["files"]:
            text = contents.get(f)
            if text is None:
                failures.append({"rule": f"共享表「{rule['name']}」", "file": f, "line": 0,
                                 "text": "文件不存在", "should_be": want})
                continue
            ls = text.splitlines()
            headers = []
            for i, l in enumerate(ls[:-1]):
                if l.strip().startswith("|") and re.match(r"^\|[\s:|-]+\|\s*$", ls[i + 1]):
                    headers.append(l)
            if not any(_norm_header(h) == _norm_header(want) for h in headers):
                failures.append({
                    "rule": f"共享表头不一致「{rule['name']}」",
                    "file": f, "line": 0,
                    "text": f"未找到表头 {want}",
                    "should_be": f"{want}　（{rule['note']}）",
                })
    return failures


# ─────────────────────────────────────────────────────────────
# 表格解析助手（供检查 13 用）
# ─────────────────────────────────────────────────────────────
# ⚠️ 与检查 11（`check_shared_headers`）共用同一口径：只认「表头行 + 紧随其后是分隔行」
#    的**真表格**。检查 11 只要表头，故它自带一段更窄的内联循环；这里还要**行号与单元格**，
#    故单独给出此助手 —— 不给检查 11 换实现，是因为它在通过状态，不值得为省十几行冒回归风险。
def _mt_cells(line):
    """把一个表格行切成单元格（去掉首尾 `|` 与空白）。"""
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _md_tables(text):
    """产出文档里的**真表格**：`[(表头 cells, [(行号, cells)], 表头行号)]`（行号从 1 起）。"""
    ls = text.splitlines()
    out = []
    i = 0
    while i < len(ls) - 1:
        # ⚠️ 分隔行必须容忍**前导缩进** —— 本库有「列表项里嵌表格」的写法
        #    （`00-总控路由.md` §一 边界 1 那张表缩进 3 格）。不容忍 → 整张表被静默漏掉
        if ls[i].strip().startswith("|") and re.match(r"^\s*\|[\s:|-]+\|\s*$", ls[i + 1]):
            head = _mt_cells(ls[i])
            rows = []
            j = i + 2
            while j < len(ls) and ls[j].strip().startswith("|"):
                rows.append((j + 1, _mt_cells(ls[j])))
                j += 1
            out.append((head, rows, i + 1))
            i = j
        else:
            i += 1
    return out


def _norm_stage(s):
    """阶段名归一口径：去掉全部空白、`*` 与反引号（故 `表情 / 动作` == `表情/动作`）。

    反引号也得去掉 —— 阶段格可能写成 `` `S0 建纲` ``，切片时会把收尾的反引号带进名字。
    """
    return re.sub(r"[\s*`]+", "", s)


def _stage_fail(rule, lno, cell, code, want, have):
    """「阶段名与权威不一致」这条失败的统一构造 —— 单格与合并格共用，免得两份文案各漂各的。

    `have` 是 `auth` 里的 `(归一值, 原件写法)` —— 比较用归一值，**提示用原件**。
    """
    return {
        "rule": f"阶段名与权威不一致「{code} {want}」",
        "file": rule["file"], "line": lno,
        "text": cell.strip(),
        "should_be": f"{code} {have[1]}　（权威：{STAGE_AUTHORITY} §一）",
    }


def check_stage_modules(files):
    """检查 13：阶段与模块归属一致性 —— 「阶段 → 负责模块」表里的两样东西必须对得上权威。

    背景（2026-09-27）：
      模块词汇在本库有**七种叫法**（全量七行清单见 `工具/README.md` §「检查 13 的由来」；
      其中**编号体系**有五套：模块号 `0N` / 目录名 `0N-名称` / 阶段号 `S0–S7` /
      代码阶段 key `建纲·资产·分镜·首帧·出片·成片` / agent 文件名 `manju-0N-*`），
      其中 `S` 号与模块号**数字不对应**：`S4 分镜`→模块 `03`、`S5 视频`→`04`、
      `S6 音频`→`05`+`04`、`S7 合规`→`06`。于是「阶段 → 负责模块」这类表最容易被写成
      **同音异义**，而且**纯文字、不会让任何东西报错**（实测两例）：
        · 阶段名被改写成同义词 —— 权威的 `S3 表情 / 动作` 另有 `S3 派生` 写法（3 处）
        · 模块归属写成另一套次序 —— `S6` 的归属有 `04 / 05` 与 `05（+04）` 两种写法
      检查 1（路径引用）/ 9（目录树）/ 10（`【0N】` 的编号与写法）都抓不到这类问题。

    权威：阶段名与门禁判据的**唯一权威**是 `STAGE_AUTHORITY`（`生产流程规范（S0-S7）.md` §一，
    该文件自己声明，`08-项目管理/` 两份文档都指向它）。本函数**只从它取权威**，
    其余收录的表一律只做**对账**。

    判定（逐条对 `STAGE_MODULE_TABLES`）：
      · 「阶段」列单元格**整格就是一个阶段标签**（`**S4 分镜**`）→ 名称须与权威逐字相同
        （只用于**没声明 `merged`** 的表）
      · 该表声明了 `"merged": True` → 阶段格**一律按 `S\d` 切片**，每片的名字也要与权威逐字相同
        （`S1 资产设计 / S2 出图 / S3 表情 / 动作` 切三次；单阶段格切一次，同样覆盖）
      · 「负责模块」列单元格里的每个 `0N 名称` → `MODULE_NUMBERS[名称]` 必须等于 `0N`

    ⚠️ 收窄规则（缺一即误报，同检查 10 的纪律）：
      a. **只扫真表格，不扫正文散文** —— 权威文件正文里有「`S3` 本集用到的 `EXP_`/`POS_`
         已建」这类句子、表格里也有「`S2/S3` 每批建完」这类格，它们都不是阶段标签
      b. **阶段名默认按「整格」匹配**（`^S\d 名称$`）—— 多阶段合并格整格比不了，
         故**合并格切片只对声明了 `"merged": True` 的表开**（现为 `08-项目管理/README.md`
         §三 与 `00-总控路由.md` §一 两张 —— 后者阶段格用 ` · ` 分隔多阶段）：
         切片后**空**的那片直接跳过（`S2/S3` 连写 —— 名字没跟在 `S2` 后面，无法归名）；
         `（…）` 里的限定词天然被切片边界截掉（`S6 音频（台词侧）` 只比主名 `音频`）。
         ⭐ 为什么必须收录它：本项目出过的两个错（`S1 设计`、`S3 派生`）**正好长在那张表里**，
         整表排除 = 守卫绕开案发现场（2026-09-27 补）
      c. **模块指称要求「两位数字 + 空白 + 中文名」** —— 裸 `02`、`04 / 05`、
         `见 §七` 之类一律跳过（这类格在 `项目目录规范.md` 里大量存在，都不是错误）
      d. **模块名不认识时报错而非静默** —— 名字不在 `MODULE_NUMBERS` 里说明它是新词或笔误，
         两种都要人看一眼（同检查 1「不许静默跳过」的纪律）。
         例外只有 `NON_PRODUCTION_MODULES` 里那三个**非生产层**（`00 总控` / `07 智能体运行时`
         / `08 项目管理`）—— 它们是路径惯例，本来就不在 `01`–`06` 的编号体系里
      e. **权威表自己也参与对账**（`STAGE_AUTHORITY` 也在 `STAGE_MODULE_TABLES` 里），
         免得「权威自己的模块列」与 `MODULE_NUMBERS` 悄悄脱钩
      f. **取不到权威阶段名就显式报错** —— `auth` 为空 = 后续对账全部静默跳过 = **假通过**。
         这条守卫是被真事故逼出来的（2026-09-27）：切片正则首版只捕数字、`auth` 的键却是
         `S1`，于是 `auth.get()` 恒 `None`，整条合并格规则空转，而校验照样报「13 类全过」。
         ⭐ 教训适用全库：**守卫「通过」不等于守卫「在跑」** —— 新加机械检查必须做反向自测
         （往真文件里注入一个错误，确认它真能被抓出来）
    """
    contents = {rel: read(ap) for ap, rel in files}
    failures = []

    # ① 先取权威阶段名（`STAGE_AUTHORITY` §一「阶段」列的整格标签）
    auth = {}
    auth_line = 0
    auth_text = contents.get(STAGE_AUTHORITY)
    if auth_text:
        for head, rows, hno in _md_tables(auth_text):
            if "阶段" not in head:
                continue
            if not auth_line:
                auth_line = hno
            si = head.index("阶段")
            for _lno, cells in rows:
                if si >= len(cells):
                    continue
                m = STAGE_CELL.match(cells[si])
                if m:
                    # 存「归一值 + 原件写法」两样：归一值只用于比较，提示一律用**原件**
                    # （只存归一值会教人写成 `S3 表情/动作`，而权威写的是 `S3 表情 / 动作`）。
                    # ⚠️ 原件只取**名称部分**，别带 `S\d` 号 —— 提示里会再拼一次号，否则变成 `S3 S3 …`
                    auth[m.group(1)] = (_norm_stage(m.group(2)), m.group(2).strip())
    # ⚠️ 一条都没取到 = **整个检查在空转**（后续对账全部走 `have is not None` 静默跳过）。
    #    「假通过」比漏报更糟，故显式报一条让人来看（文件本身缺失交给检查 1，不重复报）。
    if auth_text and not auth:
        failures.append({
            "rule": "取不到权威阶段表（阶段列没解析出任何 S0–S7）",
            "file": STAGE_AUTHORITY, "line": auth_line,
            "text": "（空）",
            "should_be": "该文件的阶段表表头须含「阶段」列、阶段格写作 `S0 建纲` 这种 —— "
                         "否则检查 13 会静默空转、报「全过」",
        })

    # ② 逐表对账
    for rule in STAGE_MODULE_TABLES:
        text = contents.get(rule["file"])
        if text is None:
            continue                      # 文件缺失交给检查 1 / 6，此处不重复报
        sc, mc = rule["stage_col"], rule["module_col"]
        for head, rows, _hno in _md_tables(text):
            if sc not in head or mc not in head:
                continue
            s_i, m_i = head.index(sc), head.index(mc)
            for lno, cells in rows:
                if s_i < len(cells):
                    if rule.get("merged"):
                        # ① 声明了 `merged` 的表**一律走切片**（合并格与单阶段格都能覆盖）。
                        #    ⚠️ 不能先试 `STAGE_CELL`：它的字符类只排除 `（`、不排除后续的 `S\d`，
                        #    于是 `S1 资产设计 / S2 出图 / S3 表情 / 动作` 会被**整格吃成一个阶段名**
                        #    （实测踩过：误报「阶段名与权威不一致「S1 资产设计/S2出图/S3表情/动作」」）
                        for seg in STAGE_FRAGMENT.finditer(cells[s_i]):
                            code = seg.group(1)
                            want = _norm_stage(seg.group(2)).strip("/、·;；：:，,")
                            if not want:
                                continue      # `S2/S3` 连写：名字没跟在号后面，无法归名（规则 b）
                            have = auth.get(code)
                            if have is not None and have[0] != want:
                                failures.append(
                                    _stage_fail(rule, lno, cells[s_i], code, want, have))
                    else:
                        # ② 默认：整格就是一个阶段标签
                        m = STAGE_CELL.match(cells[s_i])
                        if m:
                            code, want = m.group(1), _norm_stage(m.group(2))
                            have = auth.get(code)
                            if have is not None and have[0] != want:
                                failures.append(
                                    _stage_fail(rule, lno, cells[s_i], code, want, have))
                if m_i < len(cells):
                    for t in MODULE_TOKEN.finditer(cells[m_i]):
                        no, name = int(t.group(1)), t.group(2)
                        # 生产模块查 MODULE_NUMBERS；`00 总控` / `07` / `08` 三个非生产层查另一张表
                        num = MODULE_NUMBERS.get(name, NON_PRODUCTION_MODULES.get(name))
                        if num is None:
                            failures.append({
                                "rule": f"模块名不认识「{t.group(0)}」",
                                "file": rule["file"], "line": lno,
                                "text": cells[m_i].strip(),
                                "should_be": "现编模块名：" + " / ".join(MODULE_NUMBERS)
                                             + "　（非生产层另有："
                                             + " / ".join(NON_PRODUCTION_MODULES) + "）",
                            })
                        elif num != no:
                            failures.append({
                                "rule": f"模块归属错「{t.group(0)}」",
                                "file": rule["file"], "line": lno,
                                "text": cells[m_i].strip(),
                                "should_be": f"0{num} {name}",
                            })
    return failures


